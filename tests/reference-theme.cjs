const assert=require('node:assert/strict'),fs=require('node:fs');
const css=fs.readFileSync('dist/light-theme.css','utf8');
const block=css.match(/:root\{([^}]+)\}/)[1];
const tokens=Object.fromEntries([...block.matchAll(/--([\w-]+):([^;]+)/g)].map(x=>[x[1],x[2]]));
const rgb=h=>{if(h.startsWith('#'))return h.slice(1).match(/../g).map(v=>parseInt(v,16));const [r,g,b,a=1]=h.match(/[\d.]+/g).map(Number);return [r,g,b].map((v,i)=>Math.round(v*a+[4,5,9][i]*(1-a)));};
const luminance=h=>rgb(h).map(v=>v/255).map(v=>v<=.04045?v/12.92:((v+.055)/1.055)**2.4).reduce((s,v,i)=>s+v*[.2126,.7152,.0722][i],0);
const contrast=(a,b)=>{const [lo,hi]=[luminance(a),luminance(b)].sort((x,y)=>x-y);return(hi+.05)/(lo+.05)};
const [r,g,b]=rgb(tokens.bg);
assert.equal(tokens.bg,'#0B0E13');assert.equal(tokens.card,'#040509');assert.equal(tokens.line,'rgba(255,255,255,.28)');
assert.equal(tokens.ink,'#FFFFFF');assert(contrast(tokens.ink,tokens.card)>=7);
assert.equal(tokens['control-fill'],'#040509','latest reference requires dark glass controls without blue');
assert(contrast(tokens['control-ink'],tokens['control-fill'])>=4.5);
const alpha=Number(tokens['glass-fill'].match(/,([.\d]+)\)$/)[1]);
assert(alpha>=.75&&alpha<=.9,'glass must reveal the tinted backdrop instead of stacking nearly opaque gray surfaces');
assert(contrast(tokens['progress-fill'],tokens['progress-track'])>=3,'audio progress must remain distinct from its track');
console.log('PASS: reference charcoal with white glass actions, white text, translucent glass and readable control/progress contrast.');
