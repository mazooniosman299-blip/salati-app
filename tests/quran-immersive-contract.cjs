'use strict';
/** Permanent regression gate for the real Salati fullscreen, official-Mushaf reader. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const controller=read('quran-controller.js');
const plates=read('quran-printed-pages.js');
const app=read('app-source.js');
const css=read('dist/salati-ui.css');
const html=read('dist/index.html');
