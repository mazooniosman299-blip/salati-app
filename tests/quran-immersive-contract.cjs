const sourceCode=read('quran-page-audio.js');

assert(plates.includes('v1.1.1/hafs-kfqc/'),'Only a pinned official Hafs edition is accepted');
assert(plates.includes('pages: 604'),'Exactly 604 real publisher pages are required');
assert(plates.includes('King Fahd Glorious Quran Printing Complex'),'Publisher attribution missing');
assert(plates.includes('asMarkup(source, pageNumber, originalVerses)'));
assert(plates.includes("wanted.size !== available.size") || plates.includes("available.size !== wanted.size"),'Mismatch must fail closed');
assert(plates.includes("el.setAttribute('data-ayah', key)"),'Ayah tapping/recitation must keep original keys');
assert(plates.includes("if (!pageElement.isConnected"),'No stale page writes after tab change');
assert(plates.includes("getBBox()"),'Opening spread (pages 1-2) needs art-fit to avoid blank margins');
assert(plates.includes("pageNumber <= 2"),'Opening spread fit must stay specific to pages 1 and 2');
assert(plates.includes("pageElement.replaceChildren(svg,footer)"),'Publisher plate + bottom printed folio only');
assert(plates.includes("retaining verified text page."),'Network error must preserve original Quran text');
assert(controller.includes("import {mountPrintedMushaf} from './quran-printed-pages.js'"));
assert(controller.includes("void mountPrintedMushaf(page,sourceIndex+1,this.data.pages[sourceIndex])"));
assert(!controller.includes("firstPage.getBoundingClientRect().height"),'Forbidden return of page-1-height viewport sizing');
assert(!controller.includes("container.style.setProperty('--salati-quran-window-height'"),'Forbidden page-1-height CSS variable');
assert(app.includes("classList.toggle('salati-quran-immersive',active)"),'Fullscreen mode must be on Quran tab only');
assert(app.includes("new MutationObserver(sync).observe(quranPanel"),'Fullscreen state must survive tab transitions');
assert(app.includes("options.setAttribute('aria-expanded',String(open))"),'Reader options must remain accessible');
assert(css.includes('SALATI IMMERSIVE MUSHAF V1'));
assert(css.includes('body.dark.salati-quran-immersive #mushaf:not([hidden])'));
assert(css.includes('height:100dvh;'), 'Reader should occupy viewport height');
assert(css.includes('width:100vw;'),'Reader should occupy viewport width');
assert(css.includes('#qSheet #qVerses.mushaf-verses'));
assert(css.includes('overflow-y:auto;'),'Quran reading must scroll vertically');
assert(css.includes('.salati-publisher-plate'), 'Actual publisher glyphs must fill display');
assert(css.includes('.salati-printed-page > .reading-page-number'), 'Page number belongs below plate');
assert(css.includes('#mushafPlayerSlot #qTransport'));
assert(css.includes('background:#2563EB;'),'Play control must be user-approved blue');
assert(css.includes('header>.site-nav'),'Original navigation should remain usable');
assert(!css.includes('!important'), 'Never regress to competing CSS priority overrides');
assert(!html.includes('quran-approved-blue-pages.js'),'Old preview reader leaked into production');
assert(!html.includes('preview-sample-location'),'No old test location setter');
assert(html.includes('href="salati-ui.css"'),'Canonical stylesheet changed');
assert(html.includes('id="mushaf"')&&html.includes('id="times"'));
assert(source.references.some(v=>v.id==='mosque-original'&&v.status==='verified-user-asset'));
assert(sourceCode.includes('PageRecitation'));
assert(controller.includes("const footer")===false,'No accidental alternate HTML page-number authority');
console.log('PASS: source-locked 604-page printed Mushaf, viewport fullscreen, safe fallback, intact original navigation and Quran/player logic. Real browser/Android visual QA is separate.');
