'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const root='android/app/src/main/';
const read=p=>fs.readFileSync(root+p,'utf8');
const selected=read('res/drawable/widget_prayer_active.xml');
const stripDrawable=read('res/drawable/widget_glass_strip.xml');
const widgetBg=read('res/drawable/widget_background.xml');
const layout=read('res/layout/prayer_widget.xml');
const controller=read('java/com/salati/prayer/PrayerWidget.java');
const manifest=read('AndroidManifest.xml');
function attr(src,tag,key){return src.match(new RegExp('<'+tag+'\\b[^>]*android:'+key+'="([^"]+)"'))?.[1];}
assert.equal(attr(selected,'solid','color'),'#FF3D3D3D','Only time pill is medium charcoal gray');
assert.equal(attr(selected,'stroke','color'),'#FF5D5D5D','Small subtle silver outline');
assert.equal(attr(selected,'stroke','width'),'1dp');
assert.equal(attr(selected,'corners','radius'),'100dp','Pill must be fully rounded at 27dp height');
assert.equal(attr(stripDrawable,'solid','color'),'#FF242424','Strip is one matte charcoal panel');
assert.equal(attr(stripDrawable,'stroke','color'),'#FF3B3B3B','No bright border; only subtle graphite hairline');
assert.equal(attr(stripDrawable,'stroke','width'),'0.7dp');
assert.equal(attr(stripDrawable,'corners','radius'),'28dp');
assert.equal(attr(widgetBg,'stroke','color'),'#16FFFFFF','Overall widget must NOT show a strong second outer outline');
assert(layout.includes('android:layout_height="56dp" android:orientation="horizontal" android:background="@drawable/widget_glass_strip"'),'Keep all six prayers on original one row with compact 56dp reference geometry');
assert(layout.includes('android:paddingLeft="4dp" android:paddingTop="6dp" android:paddingRight="4dp"'),'Use nearly full width inside launcher cell');
assert(layout.includes('android:paddingBottom="0dp"'),'No empty area below strip in preview XML');
assert(layout.includes('android:layout_marginBottom="56dp"'),'Original mosque image must end just above compact strip, without new blank region');
assert(layout.includes('android:scaleType="centerCrop"'),'Original mosque photo must fill widget image instead of leaving letterbox gaps');
assert(layout.includes('android:gravity="top" android:baselineAligned="false"'),'Next-prayer/date group must start at top instead of floating midway');
assert(controller.includes('views.setViewPadding(R.id.widget_card,inset,inset,inset,0)'),'Native widget dynamic padding must not reintroduce bottom gap');
assert(controller.includes('int inset=Math.round((compact?2:4)'),'Native RemoteViews must not reintroduce 10dp side gutters');
assert(controller.includes('height-inset-56-8'),'Actual date layout must reserve exact same 56dp strip, not stale 77dp');
const keys=['fajr','sunrise','dhuhr','asr','maghrib','isha'];
for(const key of keys){
 const cell=layout.match(new RegExp('<LinearLayout android:id="@\\+id/widget_cell_'+key+'"[^>]*>'))?.[0];
 const label=layout.match(new RegExp('<TextView android:id="@\\+id/widget_label_'+key+'"[^>]*>'))?.[0];
 const time=layout.match(new RegExp('<TextView android:id="@\\+id/widget_'+key+'"[^>]*>'))?.[0];
 assert(cell&&label&&time,'Missing one of six original prayers: '+key);
 assert(cell.includes('android:layout_weight="1"'),'All prayer columns retain equal widths');
 assert(!cell.includes('android:background='),'Never place selected capsule behind prayer name or whole cell');
 assert(time.includes('android:minHeight="22dp"')&&time.includes('android:minWidth="38dp"'),'Only time receives compact 38x22dp, allowing full five-character Dhuhr time');
 assert(time.includes('android:paddingLeft="2dp"')&&time.includes('android:paddingRight="2dp"'),'Clock is padded inside its own pill');
 assert(!label.includes('android:background='),'Name must remain OUTSIDE selection capsule');
 assert(time.includes('android:textSize="13sp"'),'Larger 13sp time must stay intact in six narrow widget columns');
 assert(time.includes('android:ellipsize="none"'),'Never abbreviate the midday time as 11:...');
 const start=layout.indexOf('android:id="@+id/widget_'+key+'"');
 const end=layout.indexOf('/>',start);
 const oneTime=layout.slice(start,end);
 assert.equal((oneTime.match(/android:paddingTop=/g)||[]).length,1,'No duplicate XML attributes in '+key);
}
assert(controller.includes('views.setInt(valueIds[n],"setBackgroundResource",keys[n].equals(upcomingKey)?R.drawable.widget_prayer_active:0)'),'Only the upcoming TIME gets the pill and old selection clears on refresh');
assert(!controller.includes('views.setInt(cellIds[n],"setBackgroundResource"'),'Whole cell cannot get the highlight');
assert(controller.includes('!"sunrise".equals(key)'),'Sunrise must never become next prayer');
assert(controller.includes('WidgetAppearancePolicy.nextRefresh('),'Widget must refresh at upcoming prayer boundary');
assert(controller.includes('alarm.setExactAndAllowWhileIdle('),'Automatic prayer transition must be scheduled when allowed');
assert(manifest.includes('android:usesCleartextTraffic="false"'),'Android network security unchanged');
console.log('PASS: exactly six in six in one row at reference 56dp height, one short gray TIME-only pill, subtle graphite strip-only hairline and automatic prayer-to-prayer transition.');
