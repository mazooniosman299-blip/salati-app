#!/usr/bin/env python3
"""Release gate: compare packaged APK WebView assets with the exact built site.

A native-only adaptation embeds the two ORIGINAL Quran SVGs in CSS as data
URIs. Other shared JS/CSS must be identical. All packaged files must equal
prepare-android.py's staged contents, with no hidden legacy asset overrides.
Signing certificate and final APK hash are verified by the release workflow.
"""
from pathlib import Path
import base64, hashlib, sys, zipfile

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "dist"
NATIVE = ROOT / "android/app/src/main/assets/www"
apk = Path(sys.argv[1]) if len(sys.argv) == 2 else None
if not apk or not apk.is_file():
    raise SystemExit("Expected existing APK path")
if apk.stat().st_size > 25 * 1024 * 1024:
    raise SystemExit("APK exceeds Cloudflare Pages single-file limit")

required = ("index.html", "app-v1.0.109.js", "salati-ui.css",
            "quran-mushaf-markers-20261101.js",
            "images/quran-surah-ornament.svg", "images/quran-ayah-rosette.svg")
def check(ok, msg):
    if not ok:
        raise SystemExit("RELEASE BLOCKED: " + msg)

check(all((NATIVE / r).is_file() for r in required), "staged native assets missing")
with zipfile.ZipFile(apk) as archive:
    names = set(archive.namelist())
    for rel in required:
        check("assets/www/" + rel in names, "APK missing " + rel)

    checked = 0
    # No stale or substituted assets: every staged native payload present in
    # the APK must be EXACTLY what was prepared during this same build.
    for f in NATIVE.rglob("*"):
        if not f.is_file():
            continue
        rel = f.relative_to(NATIVE).as_posix()
        check("assets/www/" + rel in names, "native file omitted from APK: " + rel)
        check(archive.read("assets/www/" + rel) == f.read_bytes(),
              "native file changed when packaged: " + rel)
        checked += 1

    # Canonical CSS may differ from the website only by 2 independently
    # validated inline source SVGs, avoiding broken Android WebView images.
    expected_css = (WEB / "salati-ui.css").read_text(encoding="utf-8")
    check("!important" not in expected_css, "CSS priority migration incomplete")
    for ornament in ("quran-surah-ornament.svg", "quran-ayah-rosette.svg"):
        key = 'url("images/' + ornament + '")'
        check(expected_css.count(key) == 1,
              "native Quran SVG declaration not unique: " + ornament)
        original_svg = (WEB / "images" / ornament).read_bytes()
        check(original_svg == archive.read("assets/www/images/" + ornament),
              "original Quran artwork changed: " + ornament)
        embedded = 'url("data:image/svg+xml;base64,' + base64.b64encode(original_svg).decode("ascii") + '")'
        expected_css = expected_css.replace(key, embedded)
    check(expected_css.encode("utf-8") == archive.read("assets/www/salati-ui.css"),
          "canonical CSS does not match website plus approved 2-SVG native adaptation")

    # Every script and every other shared style in the APK is byte-for-byte
    # identical to the public site generated by the same build.
    for f in sorted(list(WEB.glob("*.js")) + list(WEB.glob("*.css"))):
        rel = f.name
        if rel == "salati-ui.css" or "assets/www/" + rel not in names:
            continue
        check(archive.read("assets/www/" + rel) == f.read_bytes(),
              "outdated shared JS/CSS: " + rel)
        checked += 1
    index = archive.read("assets/www/index.html").decode("utf-8")
    check('href="salati-ui.css"' in index, "native UI not loading canonical CSS")
    check('href="/downloads/salati-1.0.122.apk"' in (WEB/"index.html").read_text(encoding="utf-8"),
          "website points to another APK version")
    check('v1.0.122' in (WEB/"index.html").read_text(encoding="utf-8"),
          "website footer has stale version")
    for old in ("style-v1.0.", "design-restoration-v1.0.", "active-reference-nav-20261101.css"):
        check(not any(x.startswith("assets/www/" + old) for x in names),
              "obsolete CSS in Android package: " + old)
print("PASS: synchronized website and APK native assets; original Quran decorations; checked", checked)
